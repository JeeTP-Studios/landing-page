let _sid = 0;
const sid = (t: string) => `${t}-${(++_sid).toString(36)}`;

/** Construye el set de secciones por defecto de un case study.
 *  Replica el contenido legacy y agrega las secciones nuevas (challenge,
 *  methodology, gallery) para landings más completas estilo case study. */
function defaultSections(opts: {
  name: string;
  overview: string;
  goal: string;
  solution: string[];
  impact: string;
  conclusion: string;
  steps: [string, string][];
}): CaseSection[] {
  return [
    {
      id: sid("overview"),
      type: "overview",
      enabled: true,
      label: "Overview",
      title: `All about ${opts.name}`,
      body: opts.overview,
      image: "",
    },
    {
      id: sid("challenge"),
      type: "challenge",
      enabled: true,
      title: "Challenge / Problem statement",
      intro: opts.goal,
      problems: [],
      approachTitle: "Solution",
      approach: opts.solution,
      images: [],
    },
    {
      id: sid("process"),
      type: "process",
      enabled: true,
      title: "Project process",
      steps: opts.steps,
    },
    {
      id: sid("methodology"),
      type: "methodology",
      enabled: true,
      title: "Metodología",
      items: [
        {
          heading: "Impacto",
          body: opts.impact,
        },
      ],
    },
    {
      id: sid("gallery"),
      type: "gallery",
      enabled: false,
      title: "UI Design",
      layout: "grid",
      items: [],
    },
    {
      id: sid("conclusion"),
      type: "conclusion",
      enabled: true,
      title: "Conclusion",
      body: opts.conclusion,
      image: "",
    },
    {
      id: sid("cta"),
      type: "cta",
      enabled: true,
      text: "Quieres algo asi para tu marca?",
      buttonLabel: "Trabaja con nosotros",
    },
  ];
}

